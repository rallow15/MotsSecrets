const COUPE_2018 = require('../../assets/mimer/Coupe Du monde 2018.jpg');
const COUPE_1998 = require('../../assets/mimer/Coupe Du monde 1998.jpg');
const COVID_19 = require('../../assets/mimer/Covid 19.png');
const PASSE_VACCINAL = require('../../assets/mimer/Passe Vaccinal.jpg');
const OM_93 = require('../../assets/mimer/OM 93.png');
const PSG_25 = require('../../assets/mimer/PSG 25.png');
const ONE_PIECE_ACE = require('../../assets/mimer/La mort de ace.png');
const ONE_PIECE_ZORO = require('../../assets/mimer/sacrifice de zoro.png');
// JO - require dynamique pour éviter problème apostrophe (mémoïsé)
let _joImagesCache = null;
const getJoImages = () => {
  if (!_joImagesCache) {
    _joImagesCache = {
      ete: require('../../assets/mimer/jeux olympique d\'été.jpg'),
      hiver: require('../../assets/mimer/jeux olympique d\'hiver.png'),
    };
  }
  return _joImagesCache;
};

// Helper : obtenir l'image pour un mot (lieu, travail, sport, ou mimer) — mémoïsé
const _imageSourceCache = new Map();
export function getImageSource(wordName) {
  if (!wordName) return null;
  if (_imageSourceCache.has(wordName)) return _imageSourceCache.get(wordName);
  const clean = wordName.replace(/\.(jpg|jpeg|png|gif|webp)$/i, '');
  const joImages = getJoImages();

  let result = null;
  if (clean === 'Coupe Du monde 2018') result = COUPE_2018;
  else if (clean === 'Coupe Du monde 1998') result = COUPE_1998;
  else if (clean === 'Covid 19') result = COVID_19;
  else if (clean === 'Passe Vaccinal') result = PASSE_VACCINAL;
  else if (clean === 'OM 93') result = OM_93;
  else if (clean === 'PSG 25') result = PSG_25;
  else if (clean === 'La mort de ace') result = ONE_PIECE_ACE;
  else if (clean === 'sacrifice de zoro') result = ONE_PIECE_ZORO;
  else if (clean === "jeux olympique d'été") result = joImages.ete;
  else if (clean === "jeux olympique d'hiver") result = joImages.hiver;
  else result = LIEUX_IMAGES[wordName] || TRAVAIL_IMAGES[wordName] || SPORT_IMAGES[wordName] || null;

  _imageSourceCache.set(wordName, result);
  return result;
}

// Helper : obtenir l'image pour l'affichage Spyfall (lieux, travail, sport)
export function getLieuImage(wordName) {
  if (!wordName) return null;
  return LIEUX_IMAGES[wordName] || TRAVAIL_IMAGES[wordName] || SPORT_IMAGES[wordName] || null;
}